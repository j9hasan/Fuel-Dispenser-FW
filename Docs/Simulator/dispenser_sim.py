def crc8(buf):
    crc = 0
    for b in buf:
        crc = CRC8_TAB[crc ^ b]
    return crc

status_map = {
    0: "device idle",
    1: "device require to start as litre",
    2: "device require to start as sale",
    3: "device required to stop",
    4: "device busy",
    5: "device does not put nozzle back",
    6: "device status after restart"
}

current_status = 0

def input_thread():
    global current_status
    while True:
        try:
            choice = int(input("Enter status number (0-6): "))
            if choice in status_map:
                current_status = choice
                print(f"Status set to {choice}: {status_map[choice]}")
            else:
                print("Invalid choice")
        except ValueError:
            print("Invalid input")

def build_slave_response(addr, func, data_bytes):
    header = 0xA5
    length = len(data_bytes)
    frame_wo_crc = [addr, func, length] + data_bytes
    crc = crc8(frame_wo_crc)
    frame = [header] + frame_wo_crc + [crc]
    return bytes(frame)

def send_response(ser, response):
    time.sleep(0.050)  # 50 ms response delay
    ser.write(response)
    ser.flush()

def main():
    ser = serial.Serial(port="COM13", baudrate=4800, timeout=1)
    print("Fuel dispenser simulator running on COM13 at 4800 baud...")

    threading.Thread(target=input_thread, daemon=True).start()

    while True:
        byte = ser.read(1)
        if not byte:
            continue

        if byte[0] != 0xA5:
            continue

        rest = ser.read(4)
        if len(rest) < 4:
            continue

        addr, func, origin, length = rest
        master_frame = [0xA5, addr, func, origin, length]

        print("Master frame:", [hex(x) for x in master_frame])

        master_crc = crc8([addr, func, origin, length])
        print(f"Master CRC8 = {master_crc:02X}")

        # --- 4.5 Special case: origin 0x30, length 0x08 ---
        if func == 0x03 and origin == 0x30 and length == 0x08:

            data_bytes = [
                0x00, 0x58, 0x37,
                0x00, 0x12, 0x34, 0x56, 0x78
            ]

            response = build_slave_response(addr, func, data_bytes)

            send_response(ser, response)

            print(
                "Slave response:",
                response.hex(),
                "→ volume=58.37L, sale=123456.78"
            )

        # --- 4.11 Special case: offline accumulative data ---
        elif func == 0x03 and origin == 0x80 and length == 0x0E:

            data_bytes = [
                0x00, 0x00, 0x00, 0x58, 0x37,
                0x00, 0x00, 0x00, 0x12, 0x34, 0x56, 0x78,
                0x00, 0x12
            ]

            response = build_slave_response(addr, func, data_bytes)

            send_response(ser, response)

            print(
                "Slave response:",
                response.hex(),
                "→ volume=58.37L, sale=123456.78, fueling times=3"
            )

        else:
            # Normal status response
            data_bytes = [current_status]

            response = build_slave_response(addr, func, data_bytes)

            send_response(ser, response)

            print(
                "Slave response:",
                response.hex(),
                "→",
                status_map[current_status]
            )

if __name__ == "__main__":
    main()